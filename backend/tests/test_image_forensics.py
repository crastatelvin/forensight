"""Golden tests for the image analyzers (Phase 6, P6.B3).

Golden values are asserted, not just asserted-above-threshold: an analyzer whose
score drifts by a few percent between runs or library versions has changed, and a
reproducibility claim that tolerates drift is not a claim. If a change is
intentional, the model_version must change with it, and this test is where you
notice it did not.

Every fixture is generated by `fixtures_images` as a pure function of its
arguments, so the golden numbers are regenerable rather than opaque.
"""

from __future__ import annotations

import numpy as np
import pytest
from app.analysis.modules import image_ela
from app.analysis.types import AnalysisNotApplicable, Tier

from .fixtures_images import (
    make_clean_jpeg,
    make_double_compressed_jpeg,
    make_garbage,
    make_photo_jpeg,
    make_png,
    make_tampered_jpeg,
    make_tiny_jpeg,
)

# --- T6.7: every result carries the fields admissibility depends on ----------


def test_result_carries_threshold_and_version() -> None:
    result = image_ela.run(make_photo_jpeg(), {})
    assert result["threshold"] == image_ela.THRESHOLD
    assert result["model_version"] == image_ela.VERSION
    assert result["tier"] == Tier.A.value
    assert result["disclaimer"]


def test_model_version_encodes_the_jpeg_codec() -> None:
    """A libjpeg upgrade changes every score, so it must change the version.

    If this ever passes with a bare semver, the idempotency key no longer
    invalidates on a Pillow upgrade and stale ELA results get served under an
    unchanged label.
    """
    assert "ela-q75" in image_ela.VERSION
    assert "pil" in image_ela.VERSION
    assert "libjpeg" in image_ela.VERSION


# --- The core separation: does ELA see a real signal? ------------------------


def test_clean_image_is_not_flagged() -> None:
    result = image_ela.run(make_clean_jpeg(), {})
    assert result["score"] == 0.0
    assert result["score"] < result["threshold"]
    assert result["detail"]["anomalous_pixels"] == 0


def test_tampered_image_is_flagged() -> None:
    result = image_ela.run(make_tampered_jpeg(), {})
    assert result["score"] > result["threshold"] * 4, "signal is too close to the threshold"
    assert result["detail"]["anomalous_pixels"] > 1000


def test_golden_scores() -> None:
    """Pinned values. A change here is a change in measured behaviour."""
    golden = {
        "clean": (make_clean_jpeg, 0.0),
        "photo": (make_photo_jpeg, 0.008203),
        "double_compressed": (make_double_compressed_jpeg, 0.0),
        "tampered": (make_tampered_jpeg, 0.050491),
    }
    for name, (fixture, expected) in golden.items():
        actual = image_ela.run(fixture(), {})["score"]
        assert actual == pytest.approx(expected, abs=1e-5), (
            f"{name}: score moved from {expected} to {actual}. Either the algorithm "
            f"changed or the JPEG codec did — if so bump ALGORITHM_VERSION so "
            f"cached results are recomputed."
        )


def test_threshold_separates_known_cases() -> None:
    """Every fixture must land on the expected side of the threshold.

    Guards the threshold itself: a retune that lets a clean image through, or
    stops seeing the tampered one, fails here.
    """
    cases = [
        ("clean", make_clean_jpeg, False),
        ("double_compressed", make_double_compressed_jpeg, False),
        ("photo", make_photo_jpeg, False),
        ("tampered", make_tampered_jpeg, True),
    ]
    for name, fixture, expect_flagged in cases:
        score = image_ela.run(fixture(), {})["score"]
        flagged = score >= image_ela.THRESHOLD
        assert (
            flagged is expect_flagged
        ), f"{name}: score {score}, expected flagged={expect_flagged}"


# --- T6.2 in spirit: no score where the technique does not apply --------------


@pytest.mark.parametrize(
    ("label", "fixture", "expected_fragment"),
    [
        ("png", make_png, "PNG"),
        ("tiny", make_tiny_jpeg, "meaningful"),
        ("garbage", make_garbage, "did not decode"),
    ],
)
def test_non_applicable_input_refuses_to_score(label, fixture, expected_fragment) -> None:
    with pytest.raises(AnalysisNotApplicable) as exc:
        image_ela.run(fixture(), {})
    assert expected_fragment in str(exc.value)


def test_garbage_bytes_do_not_produce_a_score() -> None:
    """Undecodable evidence must never yield a confident 0.0."""
    try:
        result = image_ela.run(make_garbage(), {})
    except AnalysisNotApplicable:
        return
    pytest.fail(f"garbage produced a score: {result}")


# --- T6.5: determinism --------------------------------------------------------


def test_repeated_runs_are_identical() -> None:
    data = make_tampered_jpeg()
    runs = [image_ela.run(data, {}) for _ in range(5)]
    for other in runs[1:]:
        assert other == runs[0], "ELA is not deterministic on identical input"


def test_fixture_generation_is_deterministic() -> None:
    assert make_tampered_jpeg() == make_tampered_jpeg()
    assert make_photo_jpeg() == make_photo_jpeg()


def test_error_levels_are_finite_and_bounded() -> None:
    import io

    from PIL import Image

    levels = image_ela.error_levels(Image.open(io.BytesIO(make_photo_jpeg())))
    assert np.isfinite(levels).all()
    assert levels.min() >= 0.0
    assert levels.max() <= 255.0


def test_mad_fallback_when_error_field_is_flat() -> None:
    """A flat error field gives MAD 0; the fallback must keep the score sane."""
    flat = np.zeros((10, 10, 3), dtype=np.float32)
    stats = image_ela.analyse_levels(flat)
    assert stats["anomalous_pixel_fraction"] == 0.0
    assert stats["mad_error_level"] > 0.0


# --- Documented limitations, pinned so they cannot be forgotten ---------------


def test_ela_does_not_flag_a_wholesale_recompression() -> None:
    """Uniform double compression is a known false-positive source; we do not
    flag it, which is worth asserting because it is the technique's blind spot
    rather than a strength."""
    score = image_ela.run(make_double_compressed_jpeg(), {})["score"]
    assert score < image_ela.THRESHOLD


def test_edge_sensitivity_is_a_known_limitation() -> None:
    """Compositing any region leaves a discontinuity, and ELA sees it.

    Recorded as a known limitation rather than engineered away: an examiner must
    know that a clean score does not rule out an edit made along matching edges.
    """
    result = image_ela.run(make_tampered_jpeg(), {})
    limitations = result["detail"]["known_limitations"]
    assert any("edge" in item for item in limitations)
    assert any("absence of signal" in item for item in limitations)


def test_disclaimer_does_not_overclaim() -> None:
    """The payload must not say 'tampered'. It says regions to examine."""
    result = image_ela.run(make_tampered_jpeg(), {})
    text = (result["detail"]["interpretation"] + result["disclaimer"]).lower()
    assert "not proof" in text
    # Affirmative overclaims only: "proof of tampering" legitimately appears
    # inside its own negation, "Not proof of tampering".
    for overclaim in ("proves", "confirmed", "is tampered", "authentic image"):
        assert overclaim not in text
