#: The signature field name, so a verifier can find the field without guessing.
SIGNATURE_FIELD = "ForenSightReportSignature"

#: PAdES baseline-B, the floor rather than the ceiling.
#:
#: **Baseline-B proves the bytes have not changed since signing and says nothing about
#: *when* signing happened** — a claim only a timestamp authority can support. That limit
#: bites in practice: the moment the signing certificate expires, a baseline-B signature
#: stops establishing anything, and a report produced by a lab whose certificate later
#: lapses has nothing to fall back on.
#:
#: `REPORT_TIMESTAMP_URL` raises the floor. With a timestamp authority configured the
#: signature becomes baseline-LT — the document timestamp, the signing chain and any
#: revocation data all travel inside the PDF — and a verifier can still check it years
#: later. Without one, this module signs baseline-B and **says so on the report's face**
#: rather than implying a guarantee it cannot make.
SUBFILTER = SigSeedSubFilter.PADES

#: Signature levels, as measured rather than as configured.
BASELINE_B = "BASELINE-B"
BASELINE_T = "BASELINE-T"
BASELINE_LT = "BASELINE-LT"

#: What each level buys, for the one-line verdict.
_LEVEL_PHRASE = {
    BASELINE_B: "not timestamped, so it establishes no signing time",
    BASELINE_T: "counter-signed by a timestamp authority, but without validation material",
    BASELINE_LT: "counter-signed by a timestamp authority, with validation material embedded",
}

#: The field the document timestamp occupies when `use_pades_lta` is on. Named so a
#: verifier looking at the PDF can find it without guessing, exactly as the signature
#: field itself is.
TIMESTAMP_FIELD = "ForenSightReportTimestamp"

REASON = "ForenSight case report: content integrity as generated"
LOCATION = "Generated by ForenSight"

#: The only coverage level that means anything for a report. Anything less leaves
#: part of the document outside the signature.
_FULL_COVERAGE = "ENTIRE_FILE"

#: Modification levels that leave the signed content alone.
#:
#: **`LTA_UPDATES` is not a modification of the document.** When a signature reaches
#: baseline-LT, pyHanko appends the document timestamp and the validation material *after*
#: the signature revision, so the signature's coverage becomes `ENTIRE_REVISION` rather
#: than `ENTIRE_FILE`. Reading that as incomplete coverage — which is what treating
#: `ENTIRE_FILE` as the only acceptable value does — reports a properly signed report as
#: incomplete, and would push an operator to distrust a signature that is sound.
#:
#: `NONE` is accepted alongside it because it is what pyHanko reports for a long-term
#: archive update whose later revision adds only validation material. `OTHER`, and the
#: form-filling and annotation levels, are still refused — those change what a reader sees.
_ACCEPTABLE_MODIFICATIONS = frozenset({"NONE", "LTA_UPDATES"})


def _covers_whole_document(coverage: str, *, timestamped: bool, modification: str) -> bool:
    """Whether the signature covers the whole of the document's content.

    **`ENTIRE_FILE` is the ordinary answer and always accepted.**

    `ENTIRE_REVISION` is where the judgement lives, and it is a judgement rather than a
    lookup because the same value means two different things:

    - Without a document timestamp, it means something was appended after the signature —
      the cheapest possible edit, and the one a verifier must catch.
    - With a document timestamp, it is what a correct baseline-LT signature *always*
      reports, because pyHanko adds the countersignature and the validation material in
      later revisions. Requiring `ENTIRE_FILE` would report every long-term-validated
      report as incomplete.

    **A limit worth stating plainly.** Appending bytes to a *baseline-LT* report is not
    distinguishable from the archive update that legitimately follows it: measured,
    `total_revisions` is unchanged by an appended PDF comment, and those trailing bytes sit
    outside every signed `ByteRange` exactly as the Document Security Store does. So this
    accepts a long-term report with an appended comment. The content is still covered and
    still verifies; what is missed is the *fact* of the append, not the integrity of what
    was signed. An appended comment renders nothing, and every change that alters a page —
    content, form field, annotation — is refused above.
    """
    if coverage == _FULL_COVERAGE:
        return True
    return timestamped and modification in _ACCEPTABLE_MODIFICATIONS


class SigningUnavailable(RuntimeError):
    """No usable signing key, so no report can be produced.

    Raised rather than falling back to an unsigned PDF. A forensic report that is
    merely *downloadable* looks almost identical to one that is signed, and the
    difference is invisible until someone relies on it. Refusing to generate is the
    only way to make the gap obvious at the point it would matter.
    """


@dataclass(frozen=True)
class VerifyResult:
    """What verification found, as separate claims rather than one verdict."""

    #: The document matches its signature: both the signed bytes are unchanged
    #: (`PdfSignatureStatus.intact`) *and* the signature verifies against them
    #: (`PdfSignatureStatus.valid`).
    #:
    #: Both, because they catch different attacks. Editing the report's content
    #: leaves `intact` False. Corrupting the signature's own bytes leaves `intact`
    #: True — the signed range is untouched — and only `valid` notices. Checking one
    #: and calling the document verified misses half of what a verifier is for.
    intact: bool
    #: What the signature covers. `ENTIRE_FILE` is the only acceptable value here.
    coverage: str
    #: Whether the whole document was covered by a DocumentMDP transform.
    docmdp_ok: bool
    #: Whether the signature covers the whole of the document's *content*.
    #:
    #: Distinct from `coverage`, which is pyHanko's raw answer and says `ENTIRE_REVISION`
    #: for any signature carrying a document timestamp. This is the judgement a reader
    #: wants: the timestamp and validation material appended after the signature do not
    #: change what was signed, and a long-term-validated report must not be reported as
    #: incomplete because of them.
    covers_content: bool
    #: What was added after the signature revision, by pyHanko's difference analysis.
    #: `LTA_UPDATES` means only the timestamp and validation material. `OTHER`, or a form
    #: filling or annotation level, means content.
    modification: str
    #: Whether the signer chain validated against the supplied trust roots.
    trusted: bool
    #: The signer's certificate subject, or None when no signature was found.
    signer_subject: str | None
    #: The signing time carried by the signature, when it has one.
    #:
    #: Under PAdES baseline-B this is the *signing machine's own assertion*, not a
    #: counter-signature from a timestamp authority. It is evidence of when the
    #: signer says it signed, and nothing more, so `trusted_timestamp` is False and
    #: the report says so in those words.
    signing_time: str | None
    #: Whether a document timestamp counter-signs this signature.
    #:
    #: **Separate from `trusted`, deliberately.** The two answer different questions: a
    #: timestamp proves the signature existed at a stated time, and only a trusted TSA
    #: certificate makes that statement about anything outside this document. Collapsing
    #: them would mean an untrusted-but-present timestamp reads as no timestamp at all,
    #: losing the fact that the signature demonstrably predates a known moment.
    timestamped: bool
    #: The time the timestamp authority asserted, ISO-8601, when there is one.
    timestamp_time: str | None
    #: The timestamp authority's certificate subject, when there is one.
    tsa_subject: str | None
    #: The PAdES level this signature actually reached.
    #:
    #: Reported as a *measurement*, not an aspiration: `BASELINE-B` when only the
    #: signature is there, `BASELINE-T` with a timestamp, `BASELINE-LT` once validation
    #: material travels with the document as well. A reader is better served by the level
    #: reached than by the level the deployment was configured for.
    level: str
    #: What verification found wrong, in words fit to show a reader.
    problems: list[str]

    @property
    def verdict(self) -> str:
        """One line, honest about which of the two questions got a yes."""
        if not self.intact:
            return "FAILED — the document does not match its signature"
        if not self.covers_content:
            return (
                f"INCOMPLETE — the signature covers {self.coverage.lower()} and "
                f"{self.modification.lower().replace('_', ' ')} changes were made after it"
            )
        if not self.trusted:
            return (
                "UNVERIFIED SIGNER — the content is intact, but this certificate is "
                "not one you trust. The bytes have not changed since signing; who "
                "signed them is unconfirmed."
            )
        return (
            "VERIFIED — intact, whole-file, signed by a certificate you trust, and "
            f"{_LEVEL_PHRASE.get(self.level, 'timestamped ' + self.level.lower())}"
        )

    def as_dict(self) -> dict[str, Any]:
        return {
            "intact": self.intact,
            "coverage": self.coverage,
            "covers_content": self.covers_content,
            "modification": self.modification,
            "docmdp_ok": self.docmdp_ok,
            "trusted": self.trusted,
            "signer_subject": self.signer_subject,
            "signing_time": self.signing_time,
            "timestamped": self.timestamped,
            "timestamp_time": self.timestamp_time,
            "tsa_subject": self.tsa_subject,
            "level": self.level,
            "problems": self.problems,
            "verdict": self.verdict,
        }


_subject_line = subject_line


def as_cryptography_certificate(cert: object) -> x509.Certificate | None:
    """Normalise a certificate from either pyHanko's world or cryptography's.

    pyHanko hands back an `asn1crypto.x509.Certificate`, which is not a
    `cryptography` certificate and cannot be formatted or fingerprinted as one. Both
    expose the same DER bytes, so a re-parse is a few microseconds and buys one
    implementation of subject formatting instead of two that can drift — and one that
    silently does nothing when handed the wrong type.
    """
    if isinstance(cert, x509.Certificate):
        return cert
    dump = getattr(cert, "dump", None)
    if callable(dump):
        try:
            return x509.load_der_x509_certificate(dump())
        except Exception:  # noqa: BLE001 - fall through to "unusable"
            return None
    return None


def signing_certificate(signer: signers.PdfSigner) -> x509.Certificate:
    """The certificate a signer will sign with.

    Reached through the CMS signer rather than off the `PdfSigner` directly: pyHanko
    keeps the document-level and CMS-level halves separate, and the inner attribute
    is named `signer`, which reads like a typo for this purpose.
    """
    cms = getattr(signer, "signer", None)
    cert = as_cryptography_certificate(getattr(cms, "signing_cert", None))
    if cert is None:
        raise SigningUnavailable("the signer holds no readable signing certificate")
    return cert


def signer_subject(signer: signers.PdfSigner) -> str:
    """The certificate's subject, for printing on the report.

    A signed report should name its signer on its face. "Signed by ForenSight's
    key", with no identity attached, is the same anonymity a signature exists to
    replace.
    """
    return _subject_line(signing_certificate(signer))


def certificate_fingerprint(signer: signers.PdfSigner) -> str:
    """SHA-256 over the signing certificate's DER.

    Printed on the report so a reader can confirm they hold the same certificate
    without having to trust anything this application says about it.
    """
    return hashlib.sha256(signing_certificate(signer).public_bytes(Encoding.DER)).hexdigest()


def load_signer(
    p12_path: str | Path,
    passphrase: str,
    *,
    timestamper: Any | None = None,
    validation_context: Any | None = None,
) -> signers.PdfSigner:
    """A PDF signer backed by a PKCS#12 key and certificate.

    PKCS#12 rather than loose PEM key and cert files: it is one file with its own
    integrity protection, it cannot be half-deleted, and pyHanko supports it natively
    rather than needing key loading hand-rolled.

    **Long-term validation is opt-in and needs both halves.** `timestamper` attaches an
    RFC 3161 document timestamp and `validation_context` lets pyHanko collect the chain
    and revocation data to embed alongside it. Either alone does not reach baseline-LT:
    a timestamp with no embedded material still depends on the verifier having the same
    certificate, and embedded material with no timestamp has nothing to date it against
    once the certificate expires. Both are therefore set from configuration together, and
    `use_pades_lta` is only claimed when both are present — pyHanko will happily sign a
    signature labelled LT that is missing either half.
    """
    path = Path(p12_path)
    if not p12_path or not path.is_file():
        raise SigningUnavailable(
            f"no signing key at {p12_path or '(unset)'}. Run "
            f"scripts/provision_signer.py to create one, or set REPORT_SIGNING_P12 "
            f"to your lab's key."
        )
    try:
        # pyHanko ships no type stubs, so this call is untyped to mypy.
        load = signers.SimpleSigner.load_pkcs12
        cms: Any = load(str(path), passphrase=passphrase.encode())  # type: ignore[no-untyped-call]
    except Exception as exc:  # noqa: BLE001 - any failure here means "cannot sign"
        # The exception is not echoed verbatim: a wrong-passphrase message from a
        # crypto library can quote what it was handed.
        raise SigningUnavailable(
            f"the signing key at {path} could not be opened: {type(exc).__name__}"
        ) from exc

    if cms is None:
        # `load_pkcs12` returns None for some unreadable archives rather than
        # raising. Wrapping that None in a PdfSigner produces a signer that fails
        # later, at signing time, with an attribute error on None — which would look
        # like a fault in the report builder rather than an unreadable key.
        raise SigningUnavailable(f"the signing key at {path} is not a readable PKCS#12 archive")

    long_term = timestamper is not None and validation_context is not None

    return signers.PdfSigner(
        signers.PdfSignatureMetadata(
            field_name=SIGNATURE_FIELD,
            subfilter=SUBFILTER,
            embed_validation_info=long_term,
            use_pades_lta=long_term,
            timestamp_field_name=TIMESTAMP_FIELD if long_term else None,
            validation_context=validation_context if long_term else None,
            reason=REASON,
            location=LOCATION,
        ),
        cms,
        timestamper=timestamper,
    )


def configured_level(settings: Any) -> str:
    """The level this configuration will reach, or will not.

    Answered from configuration rather than discovered afterwards, because a deployment
    that asked for long-term validation and silently got baseline-B should be visible at
    startup rather than in a report read years later.
    """
    if timestamper_for(settings) is None:
        return BASELINE_B
    return BASELINE_LT


def timestamper_for(settings: Any) -> Any | None:
    """An RFC 3161 client, or None when none is configured.

    pyHanko's own default timeout is 5 seconds, which is short for an authority loading
    a key and a serial file on its first request — the request most likely to be the one
    that matters, because it is the one that has never been made.
    """
    url = str(getattr(settings, "report_timestamp_url", "") or "").strip()
    if not url:
        return None
    from pyhanko.sign import timestamps

    timeout = float(getattr(settings, "report_timestamp_timeout", 20.0) or 20.0)
    return timestamps.HTTPTimeStamper(url, https=url.startswith("https://"), timeout=timeout)


def _revocation_paths(settings: Any) -> list[str]:
    raw = str(getattr(settings, "report_revocation_files", "") or "")
    return [part.strip() for part in raw.split(",") if part.strip()]


def signing_validation_context(settings: Any, signer: signers.PdfSigner) -> Any:
    """A context for collecting validation material at signing time.

    **Fetching is off.** `allow_fetching` stays at its default of `False` so signing
    cannot reach out to an OCSP responder or a CRL distribution point at report time —
    which would both stall a request and send a case identifier to a third party.
    Revocation material therefore comes from what the operator supplied on disk, and the
    report says so when there is none.
    """
    from pyhanko_certvalidator import ValidationContext

    leaf = to_asn1(signing_certificate(signer))
    # The signing certificate is its own trust root here. This is right for the private
    # PKI a self-hosted lab actually runs, and it is also why the *verifier* is given its
    # own roots: this context decides what may be embedded at signing time and nothing
    # about who may later trust the result.
    roots: list[Any] = [leaf]

    # The timestamp authority is its own anchor. It has to be named here because signing
    # validates the countersignature before embedding it, and a self-signed TSA — the
    # normal air-gapped case — has no path to anything else.
    ca = str(getattr(settings, "report_timestamp_ca", "") or "").strip()
    if ca:
        from app.reports.certs import load_certificates

        path = Path(ca)
        if not path.is_file():
            raise SigningUnavailable(f"report_timestamp_ca is set to {ca}, which is not a file")
        tsa_certs = load_certificates(path.read_bytes())
        if not tsa_certs:
            raise SigningUnavailable(f"report_timestamp_ca at {ca} holds no certificate")
        roots.extend(to_asn1(cert) for cert in tsa_certs)

    bundle = str(getattr(settings, "report_signing_trust_roots", "") or "").strip()
    if bundle:
        from app.reports.certs import load_certificates

        path = Path(bundle)
        if not path.is_file():
            raise SigningUnavailable(
                f"report_signing_trust_roots is set to {bundle}, which is not a file"
            )
        roots.extend(to_asn1(c) for c in load_certificates(path.read_bytes()))

    # `crls` takes raw bytes and pyHanko parses them, so no loader is needed here — and
    # not having one is the point: this code cannot half-parse a CRL and embed the
    # fragments.
    crls: list[bytes] = []
    missing: list[str] = []
    for raw_path in _revocation_paths(settings):
        path = Path(raw_path)
        if not path.is_file():
            missing.append(raw_path)
            continue
        crls.append(path.read_bytes())
    if missing:
        raise SigningUnavailable(
            "report_revocation_files names files that do not exist: " + ", ".join(missing)
        )

    context = ValidationContext(trust_roots=roots, crls=crls or None, allow_fetching=False)
    # Asserted rather than assumed: the constructor argument and the attribute it sets are
    # differently named, so a rename upstream would silently leave fetching enabled.
    assert context.fetching_allowed is False
    return context


async def sign_pdf(pdf: bytes, signer: signers.PdfSigner) -> bytes:
    """Return `pdf` with an incremental PAdES signature appended.

    Incremental, so the original bytes are preserved verbatim and only an update is
    appended. A signature that rewrote the document would make "what was signed"
    depend on the signer's implementation rather than on the content.

    **Async, and it has to be.** pyHanko's blocking `sign_pdf` calls `asyncio.run()`
    internally, which raises outright inside a running loop — so the obvious
    implementation 500s the first time a request tries to sign a report. The async
    entry point is the only one that works from a request handler.
    """
    out = io.BytesIO()
    await signer.async_sign_pdf(IncrementalPdfFileWriter(io.BytesIO(pdf)), output=out)
    return out.getvalue()


def _signing_time(status: Any) -> str | None:
    """The signed signing-time, if the signature carries one.

    PAdES baseline-B does not require a signing-time attribute, so its absence is
    normal rather than an error. Reported as `None` and explained on the report's
    face, because "when" is precisely what this signature does not establish.
    """
    reported = getattr(status, "signer_reported_dt", None)
    return reported.isoformat() if reported is not None else None


def to_asn1(cert: x509.Certificate) -> Any:
    """A `cryptography` certificate as the `asn1crypto` one pyHanko wants.

    Easy to get wrong and silently wrong: `ValidationContext` type-hints
    `asn1crypto` certificates, but a `cryptography` certificate is accepted without
    complaint and then fails to build a path for a self-signed leaf — so passing the
    wrong type looks exactly like "this certificate is not trusted".
    """
    from asn1crypto import x509 as asn1_x509

    return asn1_x509.Certificate.load(cert.public_bytes(Encoding.DER))


def trust_context(roots: Sequence[bytes]) -> Any:
    """A validation context trusting exactly the supplied certificates.

    Parsed from all roots together because a trust bundle is routinely one PEM file
    holding several certificates, and splitting on a certificate count would
    mis-handle a concatenated bundle.
    """
    from pyhanko_certvalidator import ValidationContext

    from app.reports.certs import load_certificates

    certs = [to_asn1(c) for root in roots for c in load_certificates(root)]
    if not certs:
        raise ValueError("no usable certificate in the supplied trust roots")
    return ValidationContext(trust_roots=certs)


def _trust_problems(status: Any) -> list[str]:
    """Trust problems as a list, whichever shape pyHanko returned them in.

    `trust_problem_indic` is typed as an indicator *or* a list of them, so a single
    problem arrives un-iterable. Normalising here rather than at the call site means
    one problem cannot raise inside the verifier — which would replace a real finding
    with a traceback.
    """
    raw = getattr(status, "trust_problem_indic", None)
    if raw is None:
        return []
    if isinstance(raw, list | tuple):
        return [str(item) for item in raw]
    return [str(raw)]


def document_timestamp(pdf: bytes) -> tuple[str | None, str | None]:
    """The asserted time and TSA subject of a signed report's countersignature.

    Takes the whole PDF rather than pyHanko's signature objects, because the caller has
    bytes and no reason to know how they are parsed. Returns ``(None, None)`` for an
    unsigned or baseline-B report — an ordinary outcome, not a failure.
    """
    try:
        embedded = PdfFileReader(io.BytesIO(pdf)).embedded_signatures
    except Exception:  # noqa: BLE001 - an unreadable PDF has no timestamp to report
        return None, None
    return _document_timestamp(embedded)


#: The PDF subfilter a document timestamp carries, and its dictionary type.
#:
#: **Read from the PDF dictionary rather than from pyHanko's convenience accessors**,
#: because `EmbeddedPdfSignature` exposes neither the subfilter nor a `timestamp`
#: attribute: with `use_pades_lta` the countersignature is a *separate* signature field,
#: which is how PDF document timestamps have always worked, not an attribute hanging off the
#: signature. Reading `/SubFilter` also means this recognises a PAdES-LT document from any
#: producer, not only the ones that happened to use our field name.
TIMESTAMP_SUBFILTER = "/ETSI.RFC3161"
TIMESTAMP_TYPE = "/DocTimeStamp"


def _is_document_timestamp(field: Any) -> bool:
    """Whether this signature field is a document timestamp rather than a signature.

    Either check alone is enough for a well-formed document, but both are made because a
    producer that gets one right and the other wrong is exactly the case where guessing
    produces a confident wrong answer about a document someone may rely on.
    """
    obj = getattr(field, "sig_object", None)
    if obj is None:
        return False
    try:
        declared_type = str(obj["/Type"]) if "/Type" in obj else ""
        subfilter = str(obj["/SubFilter"]) if "/SubFilter" in obj else ""
    except Exception:  # noqa: BLE001 - an unreadable dictionary is simply not a timestamp
        return False
    return declared_type == TIMESTAMP_TYPE or subfilter == TIMESTAMP_SUBFILTER


def _document_timestamp(embedded: Sequence[Any]) -> tuple[str | None, str | None]:
    """The asserted time and the TSA's subject, from the first document timestamp.

    Returns ``(None, None)`` rather than raising: "there is no timestamp" is an ordinary
    outcome for a baseline-B report, not a failure to verify.
    """
    for field in embedded:
        if not _is_document_timestamp(field):
            continue
        asserted = getattr(field, "self_reported_timestamp", None)
        # The TSA's certificate is on the timestamp field itself, so `signer_cert` here is
        # the authority and not the report signer.
        tsa_cert = as_cryptography_certificate(getattr(field, "signer_cert", None))
        return (
            asserted.isoformat() if asserted is not None else None,
            _subject_line(tsa_cert) if tsa_cert is not None else None,
        )
    return None, None


def _has_dss(catalog: Any, embedded: Sequence[Any]) -> bool:
    """Whether the document carries a Document Security Store.

    **On the document catalog, not on the signature dictionary.** Measured against a real
    long-term report: the catalog's keys came back `['/AcroForm', '/DSS', '/Extensions',
    ...]` while the signature dictionary held only `/ByteRange /Contents /Filter /Location
    /M /Reason /SubFilter /Type`. An earlier version looked only on the signature and
    reported every long-term report as `BASELINE-T` — under-claiming the level of a report
    that had the validation material, which is the same class of error as over-claiming
    it.

    A signature-local store is also accepted, because a producer may legitimately put one
    there.
    """
    candidates = [catalog]
    candidates.extend(getattr(field, "sig_object", None) for field in embedded)
    for holder in candidates:
        if holder is None:
            continue
        try:
            if "/DSS" in holder:
                return True
        except Exception:  # noqa: BLE001, S112 - unreadable means "not present"
            continue
    return False


def _measured_level(embedded: Sequence[Any], *, timestamped: bool, catalog: Any = None) -> str:
    """The PAdES level this document actually reached.

    Measured from the document, never from the deployment's configuration: a report signed
    before a TSA was configured, or produced by another tool, must be described by what it
    carries rather than by what this installation would produce today.

    **Baseline-LT is distinguished from baseline-T by the Document Security Store** — the
    signing chain and any revocation data written into the document so a verifier needs
    nothing it was not handed. That is a structural check, not a PAdES conformance check,
    and is described as such: overclaiming the level on a document someone may rely on is
    worse than reporting the lower one.
    """
    if not timestamped:
        return BASELINE_B
    return BASELINE_LT if _has_dss(catalog, embedded) else BASELINE_T


async def verify_pdf(data: bytes, trust_roots: Sequence[bytes] | None = None) -> VerifyResult:
    """Check a report's signature, reporting integrity and trust separately.

    `trust_roots` are PEM or DER certificates the reader trusts. Omit them and
    `trusted` is False with an explanation rather than an error: a self-signed report
    is still worth verifying for integrity, and refusing to answer because the chain
    is not recognised would hide the more important question.
    """
    problems: list[str] = []

    try:
        reader = PdfFileReader(io.BytesIO(data))
        embedded = reader.embedded_signatures
    except Exception as exc:  # noqa: BLE001 - malformed input is a reportable result
        return VerifyResult(
            intact=False,
            coverage="NONE",
            covers_content=False,
            modification="UNKNOWN",
            docmdp_ok=False,
            trusted=False,
            signer_subject=None,
            signing_time=None,
            timestamped=False,
            timestamp_time=None,
            tsa_subject=None,
            level=BASELINE_B,
            problems=[f"this is not a readable PDF: {type(exc).__name__}: {exc}"],
        )

    if not embedded:
        return VerifyResult(
            intact=False,
            coverage="NONE",
            covers_content=False,
            modification="UNKNOWN",
            docmdp_ok=False,
            trusted=False,
            signer_subject=None,
            signing_time=None,
            timestamped=False,
            timestamp_time=None,
            tsa_subject=None,
            level=BASELINE_B,
            problems=[
                "no signature found. An unsigned report can be edited freely and "
                "still look exactly like this one."
            ],
        )

    # No `skip_diff`. That flag suppresses the document/signature diff, which is the
    # one check this whole module exists to perform — passed for the convenience of
    # callers who only want the certificate chain, and it means a modified document
    # can come back looking intact.
    #
    # Async for the same reason as `sign_pdf`: the blocking entry point would raise
    # inside the request handler's event loop rather than verify anything.
    #
    # The `except` is load-bearing. A byte flipped *inside the signature value* leaves
    # pyHanko unable to identify the signing certificate at all, and it raises rather
    # than returning a status. Left uncaught that turns "this document was tampered
    # with" into a 500 — and a verifier that errors out on exactly the documents it
    # exists to catch is worse than no verifier, because the failure looks like a
    # server problem and gets retried rather than believed.
    try:
        # The difference analysis is requested explicitly. Without it pyHanko cannot say
        # what was added after the signature revision, and the only honest coverage answer
        # becomes `ENTIRE_REVISION`, which on its own cannot distinguish a long-term
        # update from an appended page of content.
        status = await async_validate_pdf_signature(embedded[0], diff_policy=_DIFF_POLICY)
    except Exception as exc:  # noqa: BLE001 - any failure here means "not verified"
        return VerifyResult(
            intact=False,
            coverage="UNKNOWN",
            covers_content=False,
            modification="UNKNOWN",
            docmdp_ok=False,
            trusted=False,
            signer_subject=None,
            signing_time=None,
            timestamped=False,
            timestamp_time=None,
            tsa_subject=None,
            level=BASELINE_B,
            problems=[
                "the signature could not be read, so the document cannot be verified "
                f"as unmodified: {type(exc).__name__}: {exc}"
            ],
        )

    cert = as_cryptography_certificate(getattr(status, "signing_cert", None))
    subject = _subject_line(cert) if cert is not None else None
    signing_time = _signing_time(status)
    coverage = getattr(status.coverage, "name", "NONE") if status.coverage else "NONE"
    # A property, not a method, in this pyHanko version. Asked for unconditionally: it
    # reports what was appended after the signature revision, which is what separates a
    # clean long-term archive update from a change to the page content.
    modification = status.modification_level
    modification_name = getattr(modification, "name", "UNKNOWN") if modification else "UNKNOWN"

    # Read before coverage is judged: whether `ENTIRE_REVISION` is expected depends on
    # whether this document carries a timestamp, so the two cannot be decided separately.
    timestamp_time, tsa_subject = _document_timestamp(embedded)
    covers_content = _covers_whole_document(
        coverage,
        timestamped=timestamp_time is not None,
        modification=modification_name,
    )
    level = _measured_level(
        embedded, timestamped=timestamp_time is not None, catalog=getattr(reader, "root", None)
    )

    trusted = False
    if not trust_roots:
        problems.append("no trust roots were supplied, so the signer's identity is unconfirmed")
    else:
        try:
            # Re-validated with a context that trusts the supplied roots. Trust is
            # checked separately from integrity on purpose: a certificate that does
            # not chain still leaves the digest meaningful, and collapsing the two
            # would mean a self-signed report could never report *any* problem.
            rechecked = await async_validate_pdf_signature(
                embedded[0],
                signer_validation_context=trust_context(trust_roots),
            )
            trust_problems = _trust_problems(rechecked)
            trusted = not trust_problems
            problems.extend(trust_problems)
        except ValidationError as exc:
            problems.append(f"the signer certificate did not validate: {exc}")
        except Exception as exc:  # noqa: BLE001
            problems.append(f"trust could not be evaluated: {type(exc).__name__}: {exc}")

    if not status.intact:
        problems.append(
            "the document content does not match what was signed — it has been "
            "modified since signing"
        )
    if not status.valid:
        problems.append(
            "the signature itself does not verify against this document. The signed "
            "content may be unaltered, but the signature was altered, and a signature "
            "that does not verify attests to nothing."
        )
    if not covers_content:
        # "unsigned" stays in this sentence deliberately: it is the word a reader needs,
        # and it is the word this project's own test has been asserting on. A rephrasing
        # that is more precise but says "not covered" instead would quietly lose both.
        problems.append(
            f"the signature covers only {coverage.replace('_', ' ').lower()}, and "
            f"{modification_name.replace('_', ' ').lower()} changes were made after it; "
            "the added bytes are unsigned and not covered by the signature"
        )
    if timestamp_time is None:
        problems.append(
            "the signing time is the signing machine's own claim; no timestamp authority "
            "counter-signed it (PAdES baseline-B), so it does not independently "
            "establish when signing happened — and it will stop establishing anything "
            "once the signing certificate expires"
        )
    elif tsa_subject is None:
        problems.append(
            "a document timestamp is present but names no authority, so the asserted "
            "time cannot be attributed to anyone"
        )

    return VerifyResult(
        # Both halves: see the field's docstring. `intact` alone would call a
        # document intact whose signature had been tampered with.
        intact=bool(status.intact and status.valid),
        coverage=coverage,
        covers_content=covers_content,
        modification=modification_name,
        docmdp_ok=bool(status.docmdp_ok),
        trusted=trusted,
        signer_subject=subject,
        signing_time=signing_time,
        timestamped=timestamp_time is not None,
        timestamp_time=timestamp_time,
        tsa_subject=tsa_subject,
        level=level,
        problems=problems,
    )
